#!/usr/bin/env node
/*
 * build-clients-data.mjs — extrae la lista de clientes de clients.html y escribe
 * assets/js/clients-data.js (window.JH_CLIENTS), que es la fuente única del
 * banner infinito de la home (EN/ES).
 *
 * Incluye solo las tarjetas visibles (omite las que llevan class "is-hidden").
 * Los nombres son propios y no se traducen, por eso el archivo es compartido.
 *
 *   node tools/build-clients-data.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'clients.html';
const OUT = 'assets/js/clients-data.js';

const decode = (s) =>
  s
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const html = readFileSync(SRC, 'utf8');

const chunks = html
  .split('<article class="client-card')
  .slice(1)
  .map((chunk) => chunk.slice(0, chunk.indexOf('</article>')))
  .filter((chunk) => !/^\s*is-hidden/.test(chunk));

const items = [];
for (const chunk of chunks) {
  const name = decode((chunk.match(/class="client-name"[^>]*>([\s\S]*?)<\/[a-z0-9]+>/i) || [])[1] || '');
  const imgTag = (chunk.match(/<img[^>]*class="client-logo"[^>]*>/i) || [])[0] || '';
  const logo = (imgTag.match(/src="([^"]+)"/i) || [])[1] || '';
  if (!name || !logo) {
    console.error('FAIL — tarjeta sin nombre o sin logo:\n' + chunk.slice(0, 220));
    process.exit(1);
  }
  items.push({ name, logo: logo.replace(/^\.\.\//, '') });
}

if (!items.length) {
  console.error('FAIL — no se encontró ninguna tarjeta de cliente en ' + SRC);
  process.exit(1);
}

const out = [
  '/* AUTO-GENERATED by tools/build-clients-data.mjs — do not edit by hand.',
  '   Source: clients.html (cards without .is-hidden). Consumed by',
  '   assets/js/clients-marquee.js to render the infinite clients loop on the',
  '   home pages (EN/ES). Regenerate after editing clients.html. */',
  'window.JH_CLIENTS = [',
  ...items.map((it, i) => `  ${JSON.stringify(it)}${i < items.length - 1 ? ',' : ''}`),
  '];',
  '',
].join('\n');

writeFileSync(OUT, out);
console.log(`PASS — ${items.length} clientes → ${OUT} (${chunks.length + (html.match(/client-card is-hidden/g) || []).length} tarjetas en ${SRC}, ${(html.match(/client-card is-hidden/g) || []).length} ocultas omitidas).`);
